package relay

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/hex"
	"errors"
	"log"
	"strconv"
	"sync"
	"time"
)

type PaymentState string

const (
	StateOpen                PaymentState = "OPEN"
	StateAccepted            PaymentState = "ACCEPTED"
	StatePreimageObtained    PaymentState = "PREIMAGE_OBTAINED"
	StateSettledLocal        PaymentState = "SETTLED_LOCAL"
	StateCanceled            PaymentState = "CANCELED"
	StatePaymentFailed       PaymentState = "PAYMENT_FAILED"
	StatePaymentUnknown      PaymentState = "PAYMENT_UNKNOWN"
	StateCancellationUnknown PaymentState = "CANCELLATION_UNKNOWN"
	StateSettlementUnknown   PaymentState = "SETTLEMENT_UNKNOWN"
)

// InvoiceEvent never contains the preimage or the client's token.
// OriginalInvoicePaid remains true after PREIMAGE_OBTAINED, including when
// local settlement has an error.
type InvoiceEvent struct {
	ID                  string       `json:"id"`
	PaymentHash         string       `json:"payment_hash"`
	State               PaymentState `json:"state"`
	OriginalInvoicePaid bool         `json:"original_invoice_paid"`
	sequence            uint64
	owner               string
}

const subscriberBuffer = 128

// Tokens are generated by clients: hex or base64url, at least 32 characters.
const (
	MinTokenLength = 32
	MaxTokenLength = 256
)

var (
	ErrTokenMissing = errors.New("token required")
	ErrTokenInvalid = errors.New("token must be 32-256 characters of A-Z a-z 0-9 - _ (use e.g. `openssl rand -hex 32`)")
)

func ValidateToken(token string) error {
	if len(token) < MinTokenLength || len(token) > MaxTokenLength {
		return ErrTokenInvalid
	}
	for _, c := range token {
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '-' || c == '_') {
			return ErrTokenInvalid
		}
	}
	return nil
}

// tokenOwner returns the identifier stored with invoices: SHA-256 of the token.
func tokenOwner(token string) string {
	sum := sha256.Sum256([]byte(token))
	return hex.EncodeToString(sum[:])
}

func formatEventID(sequence uint64) string { return strconv.FormatUint(sequence, 10) }

type subscription struct {
	owner string
	all   bool
}

type subscriber struct {
	subscription
	ch chan InvoiceEvent
}

func (s subscription) sees(event InvoiceEvent) bool {
	return s.all || (s.owner != "" && s.owner == event.owner)
}

type eventHub struct {
	mu          sync.Mutex
	store       *EventStore
	sequence    uint64
	subscribers map[*subscriber]struct{}
}

// UseEventStore must be called before the relay opens circuits.
func (relay *Relay) UseEventStore(store *EventStore) error {
	h := &relay.events
	h.mu.Lock()
	defer h.mu.Unlock()
	sequence, err := store.maxSeq()
	if err != nil {
		return err
	}
	h.store = store
	h.sequence = sequence
	return nil
}

func (h *eventHub) init() {
	if h.subscribers == nil {
		h.subscribers = make(map[*subscriber]struct{})
	}
	if h.store == nil {
		store, err := OpenEventStore("")
		if err != nil {
			log.Panicln("unable to open in-memory event store:", err)
		}
		h.store = store
	}
}

// publishState records the transition and fans it out. Storage errors are
// logged but never interrupt a payment.
func (relay *Relay) publishState(hash []byte, owner string, state PaymentState) {
	h := &relay.events
	h.mu.Lock()
	defer h.mu.Unlock()
	h.init()
	key := hex.EncodeToString(hash)
	paid, err := h.store.originalPaid(key)
	if err != nil {
		log.Println("event store read error:", key, err)
	}
	h.sequence++
	event := InvoiceEvent{
		ID:                  formatEventID(h.sequence),
		PaymentHash:         key,
		State:               state,
		OriginalInvoicePaid: (paid && state != StateOpen) || state == StatePreimageObtained,
		sequence:            h.sequence,
		owner:               owner,
	}
	if err := h.store.record(event, time.Now()); err != nil {
		log.Println("event store write error:", key, state, err)
	}
	for sub := range h.subscribers {
		if !sub.sees(event) {
			continue
		}
		select {
		case sub.ch <- event:
		default:
			// A slow consumer reconnects and replays; payments never wait for it.
			delete(h.subscribers, sub)
			close(sub.ch)
		}
	}
}

func (relay *Relay) subscriptionFor(token string) (subscription, error) {
	if token == "" {
		return subscription{}, ErrTokenMissing
	}
	if relay.AdminToken != "" && subtle.ConstantTimeCompare([]byte(token), []byte(relay.AdminToken)) == 1 {
		return subscription{all: true}, nil
	}
	if err := ValidateToken(token); err != nil {
		return subscription{}, err
	}
	return subscription{owner: tokenOwner(token)}, nil
}

// SubscribeEvents atomically captures a snapshot (or stored events following
// lastID) and subscribes to future transitions, leaving no registration gap.
// A client token sees only invoices opened with it; the admin token sees all.
// If lastID is unavailable, the current state of every visible invoice is returned.
func (relay *Relay) SubscribeEvents(token, lastID string) ([]InvoiceEvent, <-chan InvoiceEvent, func(), error) {
	sub, err := relay.subscriptionFor(token)
	if err != nil {
		return nil, nil, nil, err
	}
	h := &relay.events
	h.mu.Lock()
	defer h.mu.Unlock()
	h.init()

	var initial []InvoiceEvent
	cursor, parseErr := strconv.ParseUint(lastID, 10, 64)
	replay := false
	if parseErr == nil && cursor <= h.sequence {
		minSeq, hasEvents, err := h.store.minEventSeq()
		if err != nil {
			return nil, nil, nil, err
		}
		replay = cursor == h.sequence || (hasEvents && cursor+1 >= minSeq)
	}
	if replay {
		initial, err = h.store.since(cursor, sub)
	} else {
		initial, err = h.store.current(sub)
	}
	if err != nil {
		return nil, nil, nil, err
	}

	s := &subscriber{subscription: sub, ch: make(chan InvoiceEvent, subscriberBuffer)}
	h.subscribers[s] = struct{}{}
	cancel := func() {
		h.mu.Lock()
		defer h.mu.Unlock()
		if _, exists := h.subscribers[s]; exists {
			delete(h.subscribers, s)
			close(s.ch)
		}
	}
	return initial, s.ch, cancel, nil
}
